"""Unit tests for repository discovery, mobile platform detection, and artifact exclusion."""

from __future__ import annotations

from pathlib import Path

from changeblast.discovery.scanner import (
    discover_repository,
    is_generated_source,
    is_path_excluded,
)
from changeblast.models.common import Language, Platform


class TestRepositoryDiscovery:
    """Verify Android, iOS, mixed, monorepo discovery, and generated code identification."""

    def test_exclude_build_artifacts_and_caches(self) -> None:
        assert is_path_excluded(Path("app/build/intermediates/classes.jar"))
        assert is_path_excluded(Path(".gradle/caches/modules-2/metadata.bin"))
        assert is_path_excluded(Path("DerivedData/Module/Build/Products"))
        assert is_path_excluded(Path("Pods/AFNetworking/AFNetworking.m"))
        assert is_path_excluded(Path(".build/checkouts/Alamofire"))
        assert not is_path_excluded(Path("app/src/main/kotlin/MainActivity.kt"))
        assert not is_path_excluded(Path("Sources/App/ContentView.swift"))

    def test_identify_generated_code(self) -> None:
        assert is_generated_source("app/build/generated/source/r/debug/R.java")
        assert is_generated_source("app/src/main/java/com/example/ActivityMainBinding.java")
        assert is_generated_source("DerivedData/App/Index/DataStore/ExportGenerated.swift")
        assert is_generated_source(
            "Sources/App/Normal.swift", content=b"// Generated by ProtoCompiler. DO NOT EDIT"
        )
        assert is_generated_source(
            "Sources/App/Normal.kt", content=b"/* Generated by dagger.internal */"
        )
        assert is_generated_source(
            "Sources/App/Normal.java", content=b"@javax.annotation.processing.Generated"
        )
        assert not is_generated_source(
            "app/src/main/kotlin/UserViewModel.kt", content=b"package com.example"
        )

    def test_discover_native_android_multi_module_project(self, temp_workspace: Path) -> None:
        # Create multi-module Android structure
        (temp_workspace / "settings.gradle.kts").write_text(
            'include(":app", ":core:network", ":core:model")',
            encoding="utf-8",
        )
        (temp_workspace / "build.gradle.kts").touch()

        # Create modules
        for mod in ["app", "core/network", "core/model"]:
            mod_dir = temp_workspace / mod
            (mod_dir / "src/main/kotlin").mkdir(parents=True, exist_ok=True)
            (mod_dir / "src/test/kotlin").mkdir(parents=True, exist_ok=True)
            (mod_dir / "build.gradle.kts").touch()
            (mod_dir / "src/main/kotlin/File.kt").write_text("class Foo", encoding="utf-8")

        profile = discover_repository(temp_workspace)
        assert Platform.ANDROID in profile.platforms
        assert Platform.IOS not in profile.platforms
        assert Language.KOTLIN in profile.languages
        assert len(profile.gradle_modules) == 3

        module_names = {m.name for m in profile.gradle_modules}
        assert module_names == {":app", ":core:network", ":core:model"}

        # Verify source and test roots
        assert "app/src/main/kotlin" in profile.source_roots
        assert "app/src/test/kotlin" in profile.test_roots

    def test_discover_native_ios_xcode_and_swift_package(self, temp_workspace: Path) -> None:
        # Create Xcode project and Swift Package
        (temp_workspace / "MyApp.xcodeproj").mkdir()
        (temp_workspace / "MyApp.xcodeproj/project.pbxproj").write_text(
            "/* Begin PBXNativeTarget section */\n"
            "987654 /* MyApp */ = {isa = PBXNativeTarget; name = MyApp; };\n"
            "123456 /* MyAppTests */ = {isa = PBXNativeTarget; name = MyAppTests; };\n",
            encoding="utf-8",
        )
        (temp_workspace / "Package.swift").write_text(
            "// swift-tools-version: 5.9\n"
            "import PackageDescription\n"
            'let package = Package(name: "MyCore", targets: [.target(name: "MyCore"), .testTarget(name: "MyCoreTests")])',
            encoding="utf-8",
        )
        (temp_workspace / "Sources/MyCore").mkdir(parents=True, exist_ok=True)
        (temp_workspace / "Sources/MyCore/Core.swift").write_text(
            "struct Core {}", encoding="utf-8"
        )
        (temp_workspace / "Tests/MyCoreTests").mkdir(parents=True, exist_ok=True)

        profile = discover_repository(temp_workspace)
        assert Platform.IOS in profile.platforms
        assert Platform.ANDROID not in profile.platforms
        assert Language.SWIFT in profile.languages
        assert len(profile.xcode_projects) >= 1
        assert len(profile.swift_packages) >= 1

        xcode_proj = profile.xcode_projects[0]
        assert xcode_proj.name == "MyApp"
        target_names = {t.name for t in xcode_proj.targets}
        assert "MyApp" in target_names
        assert "MyAppTests" in target_names

    def test_discover_mixed_mobile_monorepo(self, temp_workspace: Path) -> None:
        # Create both Android and iOS roots
        (temp_workspace / "android").mkdir()
        (temp_workspace / "android/build.gradle").touch()
        (temp_workspace / "android/src/main/java").mkdir(parents=True, exist_ok=True)
        (temp_workspace / "android/src/main/java/Main.java").write_text(
            "class Main {}", encoding="utf-8"
        )

        (temp_workspace / "ios").mkdir()
        (temp_workspace / "ios/App.xcodeproj").mkdir()
        (temp_workspace / "ios/Sources").mkdir(parents=True, exist_ok=True)
        (temp_workspace / "ios/Sources/App.swift").write_text("struct App {}", encoding="utf-8")

        profile = discover_repository(temp_workspace)
        assert Platform.ANDROID in profile.platforms
        assert Platform.IOS in profile.platforms
        assert profile.is_monorepo is True
        assert Language.JAVA in profile.languages
        assert Language.SWIFT in profile.languages
