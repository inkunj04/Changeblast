"""Repository discovery and structure intelligence scanner."""

from __future__ import annotations

import contextlib
import re
from pathlib import Path

from changeblast.exceptions import SecurityBoundaryViolationError
from changeblast.models.common import Language, Platform
from changeblast.models.repository import (
    GradleModule,
    RepositoryProfile,
    SwiftPackage,
    VcsMetadata,
    XcodeProject,
    XcodeTarget,
)

# Standard directory names to exclude as build artifacts or dependency caches
DEFAULT_EXCLUDED_DIRS = {
    ".git",
    ".gradle",
    "build",
    ".build",
    "DerivedData",
    "Pods",
    "Carthage",
    ".idea",
    ".vscode",
    "node_modules",
    "vendor",
    "bin",
    "obj",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
}

# Patterns indicating generated source files
GENERATED_PATH_PATTERNS = [
    re.compile(r"(^|/)(build/generated|generated)/", re.IGNORECASE),
    re.compile(r"\.build/checkouts/", re.IGNORECASE),
    re.compile(r"DerivedData/", re.IGNORECASE),
    re.compile(r"(/|^)R\.java$"),
    re.compile(r"(/|^)BuildConfig\.java$"),
    re.compile(r"Binding\.java$"),
    re.compile(r"ViewBinding\.java$"),
    re.compile(r"Generated\.(kt|java|swift)$", re.IGNORECASE),
]

GENERATED_CONTENT_MARKERS = [
    b"// Generated by",
    b"/* Generated by",
    b"// Automatically generated",
    b"// AUTO-GENERATED",
    b"@Generated",
    b"@javax.annotation.processing.Generated",
    b"@jakarta.annotation.Generated",
]


def is_path_excluded(rel_path: Path) -> bool:
    """Check if any path component matches the excluded build artifact or cache directories."""
    return any(part in DEFAULT_EXCLUDED_DIRS for part in rel_path.parts)


def is_generated_source(rel_path: str, content: bytes | None = None) -> bool:
    """Determine whether a file is auto-generated code based on path or header content."""
    normalized = rel_path.replace("\\", "/")
    for pattern in GENERATED_PATH_PATTERNS:
        if pattern.search(normalized):
            return True

    if content is not None:
        first_chunk = content[:2048]
        for marker in GENERATED_CONTENT_MARKERS:
            if marker in first_chunk:
                return True

    return False


def validate_repo_path(repo_path: Path) -> Path:
    """Resolve and validate repository path exists."""
    resolved = repo_path.resolve()
    if not resolved.exists() or not resolved.is_dir():
        raise SecurityBoundaryViolationError(f"Repository directory does not exist: {repo_path}")
    return resolved


class RepositoryScanner:
    """Discovers project structure, mobile platforms, modules, and source roots."""

    def __init__(self, root_path: Path) -> None:
        self.root_path = validate_repo_path(root_path)

    def scan(self) -> RepositoryProfile:
        """Scan repository and construct complete RepositoryProfile."""
        build_files = self._discover_build_files()
        gradle_modules = self._discover_gradle_modules()
        xcode_projects = self._discover_xcode_projects()
        swift_packages = self._discover_swift_packages()

        languages = self._detect_languages()

        platforms: list[Platform] = []
        has_android = (
            bool(gradle_modules)
            or any("gradle" in f for f in build_files)
            or self._has_android_manifest()
            or (self.root_path / "android").is_dir()
            or Language.KOTLIN in languages
            or Language.JAVA in languages
        )
        if has_android:
            platforms.append(Platform.ANDROID)

        has_ios = (
            bool(xcode_projects)
            or bool(swift_packages)
            or any("Podfile" in f for f in build_files)
            or (self.root_path / "ios").is_dir()
            or Language.SWIFT in languages
        )
        if has_ios:
            platforms.append(Platform.IOS)
        source_roots, test_roots = self._discover_source_and_test_roots(
            gradle_modules, xcode_projects, swift_packages
        )

        is_monorepo = self._detect_monorepo(gradle_modules, xcode_projects, platforms)
        vcs_meta = self._inspect_vcs()

        return RepositoryProfile(
            root_path=str(self.root_path),
            platforms=platforms,
            languages=languages,
            is_monorepo=is_monorepo,
            source_roots=sorted(list(set(source_roots))),
            test_roots=sorted(list(set(test_roots))),
            build_files=sorted(list(set(build_files))),
            gradle_modules=gradle_modules,
            xcode_projects=xcode_projects,
            swift_packages=swift_packages,
            vcs=vcs_meta,
        )

    def _has_android_manifest(self) -> bool:
        """Check for AndroidManifest.xml presence."""
        for path in self.root_path.glob("**/AndroidManifest.xml"):
            rel = path.relative_to(self.root_path)
            if not is_path_excluded(rel):
                return True
        return False

    def _discover_build_files(self) -> list[str]:
        """Find build descriptors while skipping build artifacts."""
        build_patterns = [
            "build.gradle",
            "build.gradle.kts",
            "settings.gradle",
            "settings.gradle.kts",
            "Package.swift",
            "Podfile",
            "Cartfile",
        ]
        discovered: list[str] = []
        for pattern in build_patterns:
            for p in self.root_path.glob(f"**/{pattern}"):
                rel = p.relative_to(self.root_path)
                if not is_path_excluded(rel):
                    discovered.append(str(rel).replace("\\", "/"))

        # Also find .xcodeproj and .xcworkspace
        for p in self.root_path.glob("**/*.xcodeproj"):
            rel = p.relative_to(self.root_path)
            if not is_path_excluded(rel):
                discovered.append(str(rel).replace("\\", "/"))
        for p in self.root_path.glob("**/*.xcworkspace"):
            rel = p.relative_to(self.root_path)
            if not is_path_excluded(rel):
                discovered.append(str(rel).replace("\\", "/"))

        return discovered

    def _discover_gradle_modules(self) -> list[GradleModule]:
        """Discover Gradle modules from settings.gradle / settings.gradle.kts or subdirectories."""
        modules: list[GradleModule] = []
        settings_files = [
            self.root_path / "settings.gradle.kts",
            self.root_path / "settings.gradle",
        ]

        included_module_names: set[str] = set()
        for sf in settings_files:
            if sf.exists() and sf.is_file():
                with contextlib.suppress(Exception):
                    content = sf.read_text(encoding="utf-8", errors="ignore")
                    # Match include(":app", ":core:network") or include ':app'
                    for match in re.finditer(r"include\s*\(([^)]+)\)|include\s+([^\n]+)", content):
                        raw_includes = match.group(1) or match.group(2)
                        for part in re.findall(r'["\'](:?[a-zA-Z0-9_\-:]+)["\']', raw_includes):
                            name = part if part.startswith(":") else f":{part}"
                            included_module_names.add(name)

        # Resolve paths for included modules
        for mod_name in sorted(included_module_names):
            rel_dir = mod_name.lstrip(":").replace(":", "/")
            mod_dir = self.root_path / rel_dir
            if mod_dir.is_dir():
                build_file = ""
                if (mod_dir / "build.gradle.kts").exists():
                    build_file = f"{rel_dir}/build.gradle.kts"
                elif (mod_dir / "build.gradle").exists():
                    build_file = f"{rel_dir}/build.gradle"

                source_roots, test_roots = self._find_module_roots(mod_dir, rel_dir)
                modules.append(
                    GradleModule(
                        name=mod_name,
                        path=rel_dir,
                        build_file=build_file,
                        source_roots=source_roots,
                        test_roots=test_roots,
                    )
                )

        # Fallback: scan for any directory containing build.gradle(.kts) if settings had none
        if not modules:
            for bf in self.root_path.glob("**/build.gradle*"):
                rel = bf.relative_to(self.root_path)
                if is_path_excluded(rel) or bf.parent == self.root_path:
                    continue
                mod_path = str(rel.parent).replace("\\", "/")
                name = ":" + mod_path.replace("/", ":")
                source_roots, test_roots = self._find_module_roots(bf.parent, mod_path)
                modules.append(
                    GradleModule(
                        name=name,
                        path=mod_path,
                        build_file=str(rel).replace("\\", "/"),
                        source_roots=source_roots,
                        test_roots=test_roots,
                    )
                )

        return modules

    def _find_module_roots(self, dir_path: Path, rel_prefix: str) -> tuple[list[str], list[str]]:
        """Identify standard Android source and test directories in a module."""
        src_candidates = [
            f"{rel_prefix}/src/main/kotlin",
            f"{rel_prefix}/src/main/java",
            f"{rel_prefix}/src/main",
        ]
        test_candidates = [
            f"{rel_prefix}/src/test/kotlin",
            f"{rel_prefix}/src/test/java",
            f"{rel_prefix}/src/test",
            f"{rel_prefix}/src/androidTest/kotlin",
            f"{rel_prefix}/src/androidTest/java",
            f"{rel_prefix}/src/androidTest",
        ]

        source_roots = [c for c in src_candidates if (self.root_path / c).is_dir()]
        test_roots = [c for c in test_candidates if (self.root_path / c).is_dir()]
        return source_roots, test_roots

    def _discover_xcode_projects(self) -> list[XcodeProject]:
        """Find Xcode projects, workspaces, and inspect targets."""
        projects: list[XcodeProject] = []
        for xcode_path in sorted(self.root_path.glob("**/*.xcodeproj")):
            rel = xcode_path.relative_to(self.root_path)
            if is_path_excluded(rel):
                continue

            name = xcode_path.stem
            targets: list[XcodeTarget] = []

            # Inspect project.pbxproj for target names if present
            pbxproj = xcode_path / "project.pbxproj"
            if pbxproj.exists():
                with contextlib.suppress(Exception):
                    content = pbxproj.read_text(encoding="utf-8", errors="ignore")
                    # Match target declaration lines: /* TargetName */ = {isa = PBXNativeTarget; name = TargetName; ...
                    for match in re.finditer(
                        r'isa\s*=\s*PBXNativeTarget;\s*name\s*=\s*["\']?([^"\';]+)["\']?', content
                    ):
                        tgt_name = match.group(1).strip()
                        targets.append(
                            XcodeTarget(
                                name=tgt_name,
                                target_type="application"
                                if "test" not in tgt_name.lower()
                                else "unit_test",
                                source_roots=[],
                                test_roots=[],
                            )
                        )

            if not targets:
                targets.append(XcodeTarget(name=name, target_type="application"))

            projects.append(
                XcodeProject(
                    name=name,
                    path=str(rel).replace("\\", "/"),
                    is_workspace=False,
                    targets=targets,
                )
            )

        for ws_path in sorted(self.root_path.glob("**/*.xcworkspace")):
            rel = ws_path.relative_to(self.root_path)
            if is_path_excluded(rel):
                continue
            projects.append(
                XcodeProject(
                    name=ws_path.stem,
                    path=str(rel).replace("\\", "/"),
                    is_workspace=True,
                    targets=[],
                )
            )

        return projects

    def _discover_swift_packages(self) -> list[SwiftPackage]:
        """Find Swift packages by Package.swift descriptors."""
        packages: list[SwiftPackage] = []
        for pkg_file in sorted(self.root_path.glob("**/Package.swift")):
            rel = pkg_file.relative_to(self.root_path)
            if is_path_excluded(rel):
                continue

            pkg_dir = rel.parent
            pkg_path = str(pkg_dir).replace("\\", "/") if str(pkg_dir) != "." else "."
            name = pkg_file.parent.name if pkg_path != "." else self.root_path.name
            targets: list[str] = []

            with contextlib.suppress(Exception):
                content = pkg_file.read_text(encoding="utf-8", errors="ignore")
                for match in re.finditer(
                    r'\.(?:target|executableTarget|testTarget)\s*\(\s*name\s*:\s*["\']([^"\']+)["\']',
                    content,
                ):
                    targets.append(match.group(1))

            packages.append(
                SwiftPackage(
                    name=name,
                    path=pkg_path,
                    manifest_path=str(rel).replace("\\", "/"),
                    targets=targets,
                )
            )
        return packages

    def _detect_languages(self) -> list[Language]:
        """Detect presence of Kotlin, Java, or Swift source files."""
        langs: set[Language] = set()
        for p in self.root_path.glob("**/*"):
            if not p.is_file():
                continue
            rel = p.relative_to(self.root_path)
            if is_path_excluded(rel) or is_generated_source(str(rel)):
                continue

            if p.suffix in {".kt", ".kts"}:
                langs.add(Language.KOTLIN)
            elif p.suffix == ".java":
                langs.add(Language.JAVA)
            elif p.suffix == ".swift":
                langs.add(Language.SWIFT)

            if len(langs) == 3:
                break
        return sorted(list(langs))

    def _discover_source_and_test_roots(
        self,
        gradle_modules: list[GradleModule],
        xcode_projects: list[XcodeProject],
        swift_packages: list[SwiftPackage],
    ) -> tuple[list[str], list[str]]:
        """Collate all source and test directory paths."""
        source_roots: list[str] = []
        test_roots: list[str] = []

        # From Gradle modules
        for mod in gradle_modules:
            source_roots.extend(mod.source_roots)
            test_roots.extend(mod.test_roots)

        # Top-level standard Android paths if no modules
        for cand in [
            "android/src/main/kotlin",
            "android/src/main/java",
            "android/src/main",
            "app/src/main/kotlin",
            "app/src/main/java",
            "src/main/kotlin",
            "src/main/java",
        ]:
            if (self.root_path / cand).is_dir() and cand not in source_roots:
                source_roots.append(cand)
        for cand in [
            "android/src/test/kotlin",
            "android/src/test/java",
            "android/src/test",
            "app/src/test/kotlin",
            "app/src/test/java",
            "src/test/kotlin",
            "src/test/java",
        ]:
            if (self.root_path / cand).is_dir() and cand not in test_roots:
                test_roots.append(cand)

        # Top-level standard iOS/Swift paths
        for cand in ["Sources", "Source", "Classes", "ios/Sources", "ios/Source"]:
            if (self.root_path / cand).is_dir() and cand not in source_roots:
                source_roots.append(cand)
        for cand in ["Tests", "UnitTests", "ios/Tests"]:
            if (self.root_path / cand).is_dir() and cand not in test_roots:
                test_roots.append(cand)

        return source_roots, test_roots

    def _detect_monorepo(
        self,
        gradle_modules: list[GradleModule],
        xcode_projects: list[XcodeProject],
        platforms: list[Platform],
    ) -> bool:
        """Determine whether repository functions as a mobile monorepo."""
        # Condition 1: Mixed repository containing both Android and iOS projects
        if Platform.ANDROID in platforms and Platform.IOS in platforms:
            return True
        # Condition 2: Multiple standalone apps or projects
        if len(xcode_projects) > 1:
            return True
        if len(gradle_modules) > 5:
            return True
        # Condition 3: Presence of an 'apps' or 'packages' directory with subprojects
        return bool((self.root_path / "apps").is_dir() or (self.root_path / "packages").is_dir())

    def _inspect_vcs(self) -> VcsMetadata | None:
        """Inspect local git repository metadata safely."""
        git_dir = self.root_path / ".git"
        if not git_dir.exists():
            return None

        # Read branch and commit without executing arbitrary commands if possible
        head_file = git_dir / "HEAD"
        branch: str | None = None
        commit_sha: str | None = None
        if head_file.exists():
            with contextlib.suppress(Exception):
                head_content = head_file.read_text(encoding="utf-8").strip()
                if head_content.startswith("ref: refs/heads/"):
                    branch = head_content.replace("ref: refs/heads/", "")
                    ref_file = git_dir / "refs" / "heads" / branch
                    if ref_file.exists():
                        commit_sha = ref_file.read_text(encoding="utf-8").strip()
                else:
                    commit_sha = head_content

        return VcsMetadata(
            vcs_type="git",
            branch=branch,
            commit_sha=commit_sha,
            is_dirty=False,
        )


def discover_repository(repo_path: Path) -> RepositoryProfile:
    """Public helper function to discover and profile a repository."""
    scanner = RepositoryScanner(repo_path)
    return scanner.scan()
